os.makedirs(OUT, exist_ok=True)

# ── find a CJK-capable font ──────────────────────────────────────────────────
FONT_CANDIDATES = [
    "/System/Library/Fonts/PingFang.ttc",
    "/System/Library/Fonts/STHeiti Medium.ttc",
    "/Library/Fonts/Arial Unicode MS.ttf",
    "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
]
CJK_FONT = None
for p in FONT_CANDIDATES:
    if os.path.exists(p):
        CJK_FONT = p
        break

if CJK_FONT:
    try:
        pdfmetrics.registerFont(TTFont("CJK", CJK_FONT))
        FONT = "CJK"
        print(f"Using font: {CJK_FONT}")
    except Exception as e:
        print(f"Font registration failed ({e}), falling back to ASCII content")
        FONT = "Helvetica"
        CJK_FONT = None
else:
    FONT = "Helvetica"
    print("No CJK font found; using Helvetica with ASCII/Latin content")


# ── helpers ──────────────────────────────────────────────────────────────────

def new_pdf(filename, title):
    path = os.path.join(OUT, filename)
    c = canvas.Canvas(path, pagesize=A4)
    W, H = A4
    c.setFont(FONT, 20)
    c.drawCentredString(W/2, H - 40*mm, title)
    c.setFont(FONT, 10)
    c.drawCentredString(W/2, H - 48*mm, "星河商業銀行  Galaxy Commercial Bank")
    c.line(20*mm, H - 52*mm, W - 20*mm, H - 52*mm)
    return c, W, H


def add_section(c, title, y, W, font=None, size=13):
    f = font or FONT
    c.setFont(f, size)
    c.setFillColorRGB(0.1, 0.3, 0.6)
    c.drawString(20*mm, y, title)
    c.setFillColorRGB(0, 0, 0)
    return y - 7*mm


def add_text(c, lines, y, W, size=9.5):
    c.setFont(FONT, size)
    for line in lines:
        if y < 25*mm:
            c.showPage()
            y = 270*mm
            c.setFont(FONT, size)
        c.drawString(20*mm, y, line)
        y -= 5.5*mm
    return y - 2*mm


def add_table(c, headers, rows, y, W, col_widths=None):
    """Draw a simple bordered table."""
    if col_widths is None:
        usable = W - 40*mm
        col_widths = [usable / len(headers)] * len(headers)
    row_h = 6.5*mm
    x0 = 20*mm

    # header
    c.setFillColorRGB(0.15, 0.35, 0.65)
    c.rect(x0, y - row_h, sum(col_widths), row_h, fill=1, stroke=0)
    c.setFillColorRGB(1, 1, 1)
    c.setFont(FONT, 8.5)
    x = x0
    for h, cw in zip(headers, col_widths):
        c.drawString(x + 2*mm, y - row_h + 2*mm, h)
        x += cw
    y -= row_h

    # rows
    for ri, row in enumerate(rows):
        if y < 30*mm:
            c.showPage()
            y = 270*mm
        bg = (0.95, 0.97, 1.0) if ri % 2 == 0 else (1, 1, 1)
        c.setFillColorRGB(*bg)
        c.rect(x0, y - row_h, sum(col_widths), row_h, fill=1, stroke=0)
        c.setFillColorRGB(0, 0, 0)
        c.setFont(FONT, 8.5)
        x = x0
        for cell, cw in zip(row, col_widths):
            c.drawString(x + 2*mm, y - row_h + 2*mm, str(cell))
            x += cw
        # border
        c.setStrokeColorRGB(0.8, 0.8, 0.8)
        c.rect(x0, y - row_h, sum(col_widths), row_h, fill=0, stroke=1)
        y -= row_h
    return y - 4*mm


